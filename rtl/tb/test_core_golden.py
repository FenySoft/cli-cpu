@cocotb.test()
async def test_70_golden_ldc_ret(dut):
    """hu: Smoke golden compare — LDC.I4_5 + RET, 2 lépés.
        Az RTL minden ST_DECODE-jánál ellenőrizzük a 6 belső
        regisztert a C# tracer trace-szel.
    en: Smoke golden compare — LDC.I4_5 + RET, 2 steps."""
    cocotb.start_soon(Clock(dut.clk, 10, units="ns").start())

    program = bytes([OP_LDC_I4_5, OP_RET])
    # hu: A header nélküli programhoz a Runner --entry kapcsoló nélkül
    #     futtat (entryRva=0), de a Runner header-t vár @0-án. Ezért
    #     header nélküli forma esetén a Tracer.Execute(byte[]) overload-ot
    #     hívjuk — a Runner-ben ezt az AEntryRva<0 jelzi. CLI-n keresztül
    #     ezt jelenleg nem támogatjuk explicit módon, ezért a smoke
    #     tesztben header-t adunk.
    # en: Use a header so the CLI Runner can drive entryRva=0.
    full_program = (
        bytes([0xFE, 0, 0, 1, 2, 0, 0, 0])  # header (arg=0, local=0, code_size=2)
        + program
    )
    trace = generate_golden_trace(full_program, entry_rva=0)

    # hu: A C# trace 2 lépést rögzít (LDC + RET), az RTL is 2 ST_DECODE-ot
    #     ad, és a 6 regiszter értéke megegyezik.
    assert len(trace) == 2, f"expected 2 trace entries, got {len(trace)}"

    # hu: Az RTL boot_pc = entry_rva + header_size = 0 + 8 = 8.
    await golden_compare(dut, full_program, trace, boot_pc=8)


