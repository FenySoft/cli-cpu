@cocotb.test()
async def test_72_golden_call_add(dut):
    """hu: CALL/RET golden compare — Add(2,3) hívás 8 lépéssel,
        a CallDepth 1→2→1 tranzícióval. Az r_arg_count és r_local_count
        is változik a callee-be lépéskor (0 → 2 → 0).
    en: CALL/RET golden compare — Add(2,3) call, 8 steps,
        CallDepth 1→2→1, r_arg_count and r_local_count change
        on callee entry (0 → 2 → 0)."""
    cocotb.start_soon(Clock(dut.clk, 10, units="ns").start())

    program = bytes([
        # @0..7: caller header (no args, no locals)
        0xFE, 0, 0, 2, 8, 0, 0, 0,
        # @8..15: caller body — LDC.I4_2, LDC.I4_3, CALL 16, RET
        OP_LDC_I4_2, OP_LDC_I4_3, OP_CALL, 0x10, 0x00, 0x00, 0x00, OP_RET,
        # @16..23: add() header (arg=2, local=0)
        0xFE, 2, 0, 2, 4, 0, 0, 0,
        # @24..27: add body — LDARG.0, LDARG.1, ADD, RET
        OP_LDARG_0, OP_LDARG_1, OP_ADD, OP_RET,
    ])
    trace = generate_golden_trace(program, entry_rva=0)

    assert len(trace) == 8, f"expected 8 trace entries, got {len(trace)}"
    await golden_compare(dut, program, trace, boot_pc=8, max_cycles=20000)
